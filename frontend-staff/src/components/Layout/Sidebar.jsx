const Sidebar = ({ isOpen, onClose }) => {
  const { staff, dashboardConfig } = useAuth();

  // Get sidebar keys from dashboard config; fallback to a safe default
  const sidebarKeys = dashboardConfig?.sidebar || ['dashboard'];

  const items = sidebarKeys
    .filter((key) => SIDEBAR_MAP[key])
    .map((key) => ({ key, ...SIDEBAR_MAP[key] }));

  const roleName = staff?.highest_role?.name || 'Staff';
  const initials = staff?.full_name
    ? staff.full_name.split(' ').map((n) => n[0]).slice(0, 2).join('').toUpperCase()
    : '?';

  return (
    <>
      {isOpen && (
        <div
          className="fixed inset-0 bg-black/50 z-40 lg:hidden"
          onClick={onClose}
        ></div>
      )}

      <aside
        className={`fixed lg:sticky top-0 left-0 h-screen w-64 bg-white border-r border-gray-200 z-50 transform transition-transform duration-200 ease-in-out flex flex-col ${
          isOpen ? 'translate-x-0' : '-translate-x-full lg:translate-x-0'
        }`}
      >
        <div className="flex items-center gap-3 p-6 border-b border-gray-200">
          <img src="/logo.png" alt="Arina School" className="h-10 w-10 object-contain" />
          <div>
            <p className="font-bold text-sm text-primary-900 leading-tight">ARINA SCHOOL</p>
            <p className="text-[10px] text-gray-500 tracking-widest uppercase">Staff Portal</p>
          </div>
        </div>

        {/* Staff identity strip */}
        <div className="px-6 py-4 border-b border-gray-100 bg-gray-50">
          <div className="flex items-center gap-3">
            <div className="w-9 h-9 rounded-full bg-primary-900 text-white flex items-center justify-center text-xs font-bold">
              {initials}
            </div>
            <div className="flex-1 min-w-0">
              <p className="text-sm font-semibold text-gray-900 truncate">
                {staff?.full_name}
              </p>
              <p className="text-[10px] text-gray-500 uppercase tracking-wider">
                {roleName}
              </p>
            </div>
          </div>
        </div>

        <nav className="flex-1 overflow-y-auto p-4 space-y-1">
          {items.map((item) => (
            <NavLink
              key={item.key}
              to={item.path}
              onClick={onClose}
              className={({ isActive }) =>
                isActive ? 'sidebar-link-active' : 'sidebar-link'
              }
            >
              {item.icon}
              <span>{item.label}</span>
            </NavLink>
          ))}
        </nav>

        <div className="p-4 border-t border-gray-200">
          <p className="text-[10px] text-gray-400 text-center">
            Internal use only • © {new Date().getFullYear()} Arina School
          </p>
        </div>
      </aside>
    </>
  );
};

export default Sidebar;